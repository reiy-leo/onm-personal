// 把 public/（vite 构建产物）打包成 worker-inline/assets.generated.ts，供 wrangler.inline.jsonc 部署。
// 原因：用 API Token 部署时 Static Assets 上传接口在 Hark 凭据网关下返回 401。
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative } from "node:path";

const root = new URL("../public/", import.meta.url).pathname;
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".txt": "text/plain; charset=utf-8",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".webp": "image/webp",
  ".woff2": "font/woff2",
};
const assets = {};
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    if (f.endsWith(".map")) continue;
    const t = TYPES[extname(f)] ?? "application/octet-stream";
    const bin = !(t.startsWith("text/") || t === "image/svg+xml" || t === "application/json");
    assets["/" + relative(root, p)] = { t, b: bin, d: bin ? readFileSync(p).toString("base64") : readFileSync(p, "utf8") };
  }
})(root);
writeFileSync(
  new URL("../worker-inline/assets.generated.ts", import.meta.url),
  "// Generated by scripts/build-inline-assets.mjs. Do not edit.\n" +
    `export const INLINE_ASSETS: Record<string, { t: string; b: boolean; d: string }> = ${JSON.stringify(assets)};\n`,
);
console.log(`inlined ${Object.keys(assets).length} files`);
